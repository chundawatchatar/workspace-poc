import { lstatSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

/**
 * The files of a built UI folder, by URL path (`/assets/index-abc.js`) to their path on disk, sorted. Dotfiles and
 * dot folders are left out, since the host never serves them. Anything that is not a plain file or folder, such as
 * a symlink, throws: a build has none, and following one could embed a file from outside the build.
 */
export function collectUiFiles(dir: string): Record<string, string> {
  const files: Record<string, string> = {}
  const walk = (folder: string, urlPath: string) => {
    for (const name of readdirSync(folder).sort()) {
      if (name.startsWith('.')) continue
      const path = join(folder, name)
      const stat = lstatSync(path)
      if (stat.isDirectory()) walk(path, `${urlPath}${name}/`)
      else if (stat.isFile()) files[`${urlPath}${name}`] = path
      else throw new Error(`The UI build has ${path}, which is not a plain file or folder`)
    }
  }
  walk(dir, '/')
  if (!files['/index.html']) throw new Error(`The UI build in ${dir} has no index.html`)
  return files
}

/**
 * The source of the executable's entry point: it imports every UI file as an embedded file, hands their embedded
 * paths to `embedUi` (`registry`), then runs `main`, the host's real entry point. `main` is imported only after the
 * files are handed in, so nothing reads them earlier. Every path is absolute.
 */
export function embeddedEntrySource({
  files,
  registry,
  main,
}: {
  files: Record<string, string>
  registry: string
  main: string
}): string {
  const entries = Object.entries(files)
  return [
    '// Generated by scripts/package-host.ts. Do not edit.',
    `import { embedUi } from ${JSON.stringify(registry)}`,
    ...entries.map(([, path], i) => `import file${i} from ${JSON.stringify(path)} with { type: 'file' }`),
    '',
    'embedUi({',
    ...entries.map(([urlPath], i) => `  ${JSON.stringify(urlPath)}: file${i},`),
    '})',
    `await import(${JSON.stringify(main)})`,
    '',
  ].join('\n')
}
